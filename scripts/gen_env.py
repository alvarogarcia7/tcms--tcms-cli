#!/usr/bin/env python3.14
"""
Create or update .env from the top-level `variables:` of .gitlab-ci.yml.

- A variable already assigned in .env is rewritten in place with the CI value.
- A variable missing from .env is appended at the end.
- Every other line of .env (local settings, comments, blank lines) is kept as it is.

Usage: uv run python3.14 scripts/gen_env.py [--ci .gitlab-ci.yml] [--env .env]
"""

import argparse
import re
import sys
from pathlib import Path

import yaml

ASSIGNMENT = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)=")
PLAIN_VALUE = re.compile(r"^[A-Za-z0-9_./:@%+,=~${}-]*$")
# GitLab predefined variables (CI_PROJECT_DIR, ...) have no meaning on a developer machine. Written to
# .env, make would export the wrong value to every recipe, so such variables are skipped.
CI_PREDEFINED = re.compile(r"\$\{?CI_")
HEADER = "# Variables from .gitlab-ci.yml (generated by make gen-env)"


def render(value):
    """Return the right-hand side of KEY=value, quoting only when the value needs it."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    text = str(value)
    if PLAIN_VALUE.match(text):
        return text
    return "'" + text.replace("'", "'\\''") + "'"


def load_ci_variables(ci_path):
    """Return the rendered CI variables to write, and the names skipped as GitLab-only."""
    with open(ci_path, encoding="utf-8") as handle:
        document = yaml.safe_load(handle) or {}
    variables = document.get("variables") or {}
    skipped = [
        key for key, value in variables.items() if CI_PREDEFINED.search(str(value))
    ]
    rendered = {
        key: render(value) for key, value in variables.items() if key not in skipped
    }
    return rendered, skipped


def update_lines(lines, variables):
    """Rewrite assignments that CI defines; return the new lines and the keys still missing."""
    pending = dict(variables)
    updated = []
    for line in lines:
        match = ASSIGNMENT.match(line)
        if match and match.group(1) in variables:
            key = match.group(1)
            updated.append(f"{key}={variables[key]}")
            pending.pop(key, None)
        else:
            updated.append(line)
    return updated, pending


def gen_env(ci_path, env_path):
    variables, skipped = load_ci_variables(ci_path)
    env_file = Path(env_path)
    existing = (
        env_file.read_text(encoding="utf-8").splitlines() if env_file.exists() else []
    )

    lines, missing = update_lines(existing, variables)

    if missing:
        if lines and lines[-1].strip():
            lines.append("")
        lines.append(HEADER)
        lines.extend(f"{key}={value}" for key, value in missing.items())

    env_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        f"Wrote {env_path}: {len(variables) - len(missing)} updated, {len(missing)} added "
        f"from {ci_path}",
        file=sys.stderr,
    )
    if skipped:
        print(
            f"Skipped GitLab-only variables (use CI_* paths): {', '.join(skipped)}",
            file=sys.stderr,
        )


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--ci", default=".gitlab-ci.yml", help="GitLab CI file to read variables from"
    )
    parser.add_argument("--env", default=".env", help=".env file to create or update")
    args = parser.parse_args()
    gen_env(args.ci, args.env)


if __name__ == "__main__":
    main()
